SELECT ININVERSAOSALDO, COCONTACONTABIL, COCONTACORRENTE, SALDO, COUG
FROM (
  SELECT O978241.ININVERSAOSALDO,
         O996998.COCONTACONTABIL,
         O996998.COCONTACORRENTE,
         DECODE(SUBSTR(O996998.COCONTACONTABIL,1,1),
                1,O996998.VADEBITO-O996998.VACREDITO,
                3,O996998.VADEBITO-O996998.VACREDITO,
                5,O996998.VADEBITO-O996998.VACREDITO,
                8,O996998.VADEBITO-O996998.VACREDITO,
                O996998.VACREDITO-O996998.VADEBITO) AS SALDO,
         O996998.COUG
  FROM MIL2026.VCONTACONTABIL O978241, MIL2026.SALDOCONTABIL O996998
  WHERE O978241.COCONTACONTABIL = O996998.COCONTACONTABIL
    AND O978241.INSALDOCONTABIL = 'D'
    AND O978241.ININVERSAOSALDO = 'N'
    AND O978241.COCONTACONTABIL BETWEEN 100000000 AND 199999999
    AND O996998.INMES = {MES}
)
WHERE SALDO < 0
ORDER BY COUG, COCONTACONTABIL, COCONTACORRENTE
;
